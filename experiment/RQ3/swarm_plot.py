# 定义计算总和的函数
def calculate_all_sums(data):
    """
    计算嵌套字典中每个层级的总和
    :param data: 嵌套字典数据
    :return: 包含各层级总和的字典
    """
    # 存储所有总和结果
    sum_results = {}
    
    # 遍历第一层（gpt-4o tokens/deepseek tokens）
    for main_key, main_value in data.items():
        sum_results[main_key] = {}
        total_main = 0  # 存储当前main_key的总合计
        
        # 遍历第二层（Bank(r)/Market(r)等）
        for sub_key, num_list in main_value.items():
            # 计算当前子列表的总和
            sub_sum = sum(num_list)
            sum_results[main_key][sub_key] = sub_sum
            total_main += sub_sum
        
        # 添加当前main_key的总合计
        sum_results[main_key]['总计'] = total_main
    
    return sum_results

# 定义格式化输出结果的函数
def print_sum_results(sum_results):
    """
    格式化打印总和结果
    :param sum_results: 计算得到的总和字典
    """
    print("=== 各键值对应的总和计算结果 ===\n")
    
    for main_key, sub_results in sum_results.items():
        print(f"【{main_key}】")
        # 按键排序输出（排除总计）
        sorted_sub_keys = sorted([k for k in sub_results.keys() if k != '总计'])
        for sub_key in sorted_sub_keys:
            # 格式化数字，添加千分位分隔符
            formatted_sum = f"{sub_results[sub_key]:,}"
            print(f"  {sub_key:<10} : {formatted_sum}")
        
        # 输出总计
        formatted_total = f"{sub_results['总计']:,}"
        print(f"  {'总计':<10} : {formatted_total}\n")

