# ===================== 3. 数据校验与格式化 =====================
def format_data(real_data):
    gpt4o_data = {'Category': [], 'gpt-4o tokens': [], 'Method': []}
    deepseek_data = {'Category': [], 'deepseek tokens': [], 'Method': []}
    
    for category, values in real_data['gpt-4o tokens'].items():
        method = 'OpenRCA' if '(r)' in category else 'Original'
        gpt4o_data['Category'].extend([category]*len(values))
        gpt4o_data['gpt-4o tokens'].extend([v/1000000 for v in values])
        gpt4o_data['Method'].extend([method]*len(values))
    
    for category, values in real_data['deepseek tokens'].items():
        method = 'OpenRCA' if '(r)' in category else 'Original'
        deepseek_data['Category'].extend([category]*len(values))
        deepseek_data['deepseek tokens'].extend([v/1000000 for v in values])
        deepseek_data['Method'].extend([method]*len(values))
    
    gpt4o_df = pd.DataFrame(gpt4o_data)
    deepseek_df = pd.DataFrame(deepseek_data)
    
    return gpt4o_df, deepseek_df

